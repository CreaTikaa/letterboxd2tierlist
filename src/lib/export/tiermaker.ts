import JSZip from 'jszip'
import { runPool } from '../pool'
import { posterUrl } from '../tmdb/client'
import type { Film, Match } from '../types'
import { canvasToBlob, createCanvas, drawCaption, drawCover, drawPlaceholder, loadBitmap } from './canvas'

export type Caption = 'none' | 'title' | 'title-rating'

// TierMaker limits: 500 images and 50 MB per upload (3,000 per template). Keep a margin on size.
export const MAX_FILES_PER_BATCH = 500
export const MAX_BYTES_PER_BATCH = 45 * 1024 * 1024
export const TIERMAKER_TEMPLATE_LIMIT = 3000

const POSTER_W = 342
const POSTER_H = 513

export function safeFileName(name: string): string {
  const cleaned = name
    // oxlint-disable-next-line no-control-regex -- control characters are invalid in file names
    .replace(/[<>:"/\\|?*\u0000-\u001f]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[. ]+$/, '')
    .slice(0, 120)
  return cleaned || 'film'
}

/** Appends " (2)", " (3)"… to repeated names (compared case-insensitively, as Windows does). */
export function uniqueNames(names: string[]): string[] {
  const seen = new Map<string, number>()
  return names.map((name) => {
    const key = name.toLowerCase()
    const count = (seen.get(key) ?? 0) + 1
    seen.set(key, count)
    return count === 1 ? name : `${name} (${count})`
  })
}

/** Splits files (given by size, in order) into upload batches within TierMaker's limits. */
export function planBatches(sizes: number[], maxCount = MAX_FILES_PER_BATCH, maxBytes = MAX_BYTES_PER_BATCH): number[][] {
  const batches: number[][] = []
  let current: number[] = []
  let bytes = 0
  sizes.forEach((size, i) => {
    if (current.length && (current.length >= maxCount || bytes + size > maxBytes)) {
      batches.push(current)
      current = []
      bytes = 0
    }
    current.push(i)
    bytes += size
  })
  if (current.length) batches.push(current)
  return batches
}

async function renderPoster(film: Film, match: Match | undefined, caption: Caption): Promise<Blob> {
  const posterPath = match?.status === 'matched' ? match.posterPath : null

  // Untouched posters can be passed through without re-encoding.
  if (posterPath && caption === 'none') {
    const res = await fetch(posterUrl(posterPath, 'w342'))
    if (res.ok) return res.blob()
  }

  const { canvas, ctx } = createCanvas(POSTER_W, POSTER_H)
  let image: ImageBitmap | null = null
  if (posterPath) {
    try {
      image = await loadBitmap(posterUrl(posterPath, 'w342'))
    } catch {
      image = null
    }
  }
  if (image) {
    drawCover(ctx, image, 0, 0, POSTER_W, POSTER_H)
    image.close()
    if (caption !== 'none') drawCaption(ctx, film, caption === 'title-rating', 0, 0, POSTER_W, POSTER_H)
  } else {
    // The placeholder already shows the title; add the rating line when asked for.
    drawPlaceholder(ctx, film, 0, 0, POSTER_W, POSTER_H)
    if (caption === 'title-rating') drawCaption(ctx, { ...film, name: '', year: null }, true, 0, 0, POSTER_W, POSTER_H)
  }
  return canvasToBlob(canvas, 'image/jpeg', 0.9)
}

const README = `How to use these images on TierMaker
=====================================

1. Go to https://tiermaker.com/create and sign in.
2. Fill in the template name/category, then upload the images
   (drag the files from ONE batch folder at a time: max 500 images / 50 MB per upload).
3. Publish the template. For more than one batch, edit the template and upload the
   next batch folder. Don't re-upload images that are already in it, or they'll be duplicated.
4. TierMaker allows up to 3,000 images per template.

Generated by letterboxd2tierlist. Posters from TMDB (https://www.themoviedb.org).
`

export interface TierMakerZip {
  blob: Blob
  fileCount: number
  batchCount: number
}

export async function buildTierMakerZip(
  films: Film[],
  matches: Record<string, Match>,
  caption: Caption,
  onProgress?: (done: number, total: number) => void,
): Promise<TierMakerZip> {
  const blobs: Blob[] = new Array(films.length)
  let done = 0
  await runPool(films, 8, async (film, i) => {
    blobs[i] = await renderPoster(film, matches[film.id], caption)
    onProgress?.(++done, films.length)
  })

  const names = uniqueNames(films.map((f) => safeFileName(f.year ? `${f.name} (${f.year})` : f.name)))
  const batches = planBatches(blobs.map((b) => b.size))
  const zip = new JSZip()
  zip.file('README.txt', README)
  batches.forEach((batch, b) => {
    const folder = batches.length > 1 ? zip.folder(`batch-${String(b + 1).padStart(2, '0')}`)! : zip
    for (const i of batch) {
      const ext = blobs[i].type === 'image/png' ? 'png' : 'jpg'
      folder.file(`${names[i]}.${ext}`, blobs[i])
    }
  })
  // Posters are already compressed; storing them is much faster than deflating.
  const blob = await zip.generateAsync({ type: 'blob', compression: 'STORE' })
  return { blob, fileCount: films.length, batchCount: batches.length }
}
